"""現在地 → 都道府県の推定に使う格子表（frontend/public/data/pref-grid.json）を作る。

## なぜ格子表か

「現在地から選ぶ」は座標を外へ送らない（逆ジオコーダ API を使わない）約束なので、端末内で県を決める。
最初は県庁所在地などの代表点への最近傍で決めていたが、同梱の避難所データ（国土地理院・115,674 件）を
正解にして測ると正解率 88.4%（愛知→静岡・宮城→岩手などの取り違え）だった。
誤った県を確定すると、その県の特別警報を見落とす。

そこで避難所の住所（先頭が都道府県名）と座標から、0.05° 格子ごとの多数決で県を決める表を作る。
フロントは「現在地から選ぶ」を押したときだけこの静的ファイルを同じオリジンから取得する
（リクエストに座標は載らない）。

## 引き方（frontend/src/lib/prefGrid.ts と同じ規則。変えるなら両方）

- マスの番号は `floor(lat * 20)`, `floor(lon * 20)`（0.05°）。round ではなく floor
  （Python の round は偶数丸めで JS の Math.round と境界でずれるため）
- マスに値があればそれ。無ければ半径 1〜5 マスの正方形の中の多数決（同数は県コードの小さい方）。
  5 マス以内に何も無ければ null（国外・遠い海上）

## 出力の形（小さく符号化）

```
{"version": 1, "cellsPerDegree": 20,
 "rows": [[latIdx, lonStart, code, len, code, len, ...], ...],
 "meta": {...出典...}}
```

緯度の行ごとに、経度の開始マスから「県コード（JIS 2 桁の数値。0 は空き）と連続数」を並べる。

## 使い方

    python scripts/generate_pref_grid.py            # 生成して正解率を表示
    python scripts/generate_pref_grid.py --check    # 生成物が今のデータから作り直したものと一致するか（CI 用）

データの出典表示（PDL1.0）は meta に入れる。
"""
from __future__ import annotations

import argparse
import gzip
import json
import math
import random
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHELTERS = ROOT / "backend" / "data" / "shelters" / "shelters.json.gz"
OUTPUT = ROOT / "frontend" / "public" / "data" / "pref-grid.json"

CELLS_PER_DEGREE = 20  # 0.05°
MAX_RING = 5

PREFECTURE_NAMES = (
    "北海道 青森県 岩手県 宮城県 秋田県 山形県 福島県 茨城県 栃木県 群馬県 埼玉県 千葉県 東京都 神奈川県 "
    "新潟県 富山県 石川県 福井県 山梨県 長野県 岐阜県 静岡県 愛知県 三重県 滋賀県 京都府 大阪府 兵庫県 "
    "奈良県 和歌山県 鳥取県 島根県 岡山県 広島県 山口県 徳島県 香川県 愛媛県 高知県 福岡県 佐賀県 長崎県 "
    "熊本県 大分県 宮崎県 鹿児島県 沖縄県"
).split()
assert len(PREFECTURE_NAMES) == 47


def load_points(path: Path = SHELTERS) -> tuple[list[tuple[float, float, int]], dict]:
    """(lat, lon, 県コード 1..47) の一覧と、元データの meta を返す。住所から県が引けない行は捨てる。"""
    with gzip.open(path, "rt", encoding="utf-8") as f:
        data = json.load(f)
    fields = data["fields"]
    if isinstance(fields, list):
        idx = {name: i for i, name in enumerate(fields)}
    else:  # 件数だけが入っている形（id,name,address,lat,lon,types の順）
        idx = {"address": 2, "lat": 3, "lon": 4}
    points = []
    for row in data["shelters"]:
        address = row[idx["address"]] or ""
        lat, lon = row[idx["lat"]], row[idx["lon"]]
        if lat is None or lon is None:
            continue
        code = next((i + 1 for i, name in enumerate(PREFECTURE_NAMES) if address.startswith(name)), None)
        if code is not None:
            points.append((float(lat), float(lon), code))
    return points, data.get("meta", {})


def cell_of(lat: float, lon: float) -> tuple[int, int]:
    return math.floor(lat * CELLS_PER_DEGREE), math.floor(lon * CELLS_PER_DEGREE)


def majority(counter: Counter) -> int:
    """最多の県コード。同数は小さいコード（並び順に依存させない）"""
    best = max(counter.values())
    return min(code for code, n in counter.items() if n == best)


def build_grid(points) -> dict[tuple[int, int], int]:
    cells: dict[tuple[int, int], Counter] = defaultdict(Counter)
    for lat, lon, code in points:
        cells[cell_of(lat, lon)][code] += 1
    return {key: majority(c) for key, c in cells.items()}


def lookup(grid: dict[tuple[int, int], int], lat: float, lon: float) -> int | None:
    i, j = cell_of(lat, lon)
    if (i, j) in grid:
        return grid[(i, j)]
    for r in range(1, MAX_RING + 1):
        counts = Counter(
            grid[(i + di, j + dj)]
            for di in range(-r, r + 1)
            for dj in range(-r, r + 1)
            if (i + di, j + dj) in grid
        )
        if counts:
            return majority(counts)
    return None


def encode(grid: dict[tuple[int, int], int], meta: dict) -> dict:
    rows = []
    for lat_idx in sorted({i for i, _ in grid}):
        lons = sorted(j for i, j in grid if i == lat_idx)
        start, end = lons[0], lons[-1]
        runs: list[int] = []
        for j in range(start, end + 1):
            code = grid.get((lat_idx, j), 0)
            if runs and runs[-2] == code:
                runs[-1] += 1
            else:
                runs += [code, 1]
        rows.append([lat_idx, start, *runs])
    return {
        "version": 1,
        "cellsPerDegree": CELLS_PER_DEGREE,
        "rows": rows,
        "meta": {
            "description": "0.05° grid -> prefecture (JIS X 0401 code, 0 = empty). Generated by scripts/generate_pref_grid.py",
            "cells": len(grid),
            "source": meta.get("source"),
            "license": meta.get("license"),
            "attribution": meta.get("attribution"),
            "processing": "国土地理院「指定緊急避難場所データ」を加工して作成（住所の都道府県と座標から格子ごとの多数決）",
        },
    }


def serialize(obj: dict) -> str:
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":")) + "\n"


def accuracy(grid, points) -> float:
    ok = sum(1 for lat, lon, code in points if lookup(grid, lat, lon) == code)
    return ok / len(points)


def generate_text() -> str:
    points, meta = load_points()
    return serialize(encode(build_grid(points), meta))


def is_up_to_date(text: str | None = None) -> bool:
    """生成物が今のデータから作り直したものと一致するか。

    改行は比べない（Windows の autocrlf で取り出すと CRLF になるため）。
    """
    if text is None:
        text = generate_text()
    if not OUTPUT.exists():
        return False
    current = OUTPUT.read_bytes().decode("utf-8").replace("\r\n", "\n")
    return current == text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="生成物が最新か検査する（書き込まない）")
    args = parser.parse_args()

    points, meta = load_points()
    grid = build_grid(points)
    text = serialize(encode(grid, meta))

    if args.check:
        if not is_up_to_date(text):
            print(f"NG: {OUTPUT.relative_to(ROOT)} が古い。python scripts/generate_pref_grid.py で作り直す")
            return 1
        print(f"OK: {OUTPUT.relative_to(ROOT)} は最新（{len(grid)} マス）")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")

    # 正解率: 全件（表を作ったデータそのもので引く）と、半分で作って残り半分で測る汎化
    shuffled = points[:]
    random.Random(1).shuffle(shuffled)
    half = len(shuffled) // 2
    held_grid = build_grid(shuffled[:half])
    print(f"points={len(points)} cells={len(grid)} bytes={len(text.encode('utf-8'))}")
    print(f"accuracy_all={accuracy(grid, points):.2%} accuracy_heldout={accuracy(held_grid, shuffled[half:]):.2%}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
